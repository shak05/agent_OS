"""DocGenAgent: turns research text into a small .pptx inside the sandbox."""
from __future__ import annotations

import re
from typing import Any, Optional

from pptx import Presentation
from pptx.util import Pt

from runtime.agent import Agent


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "report"


class DocGenAgent(Agent):
    """Builds a title slide, a summary slide, a key-points slide and a sources slide."""

    def __init__(self, name: str = "DocGenAgent", agent_id: Optional[str] = None) -> None:
        super().__init__(name, permissions=["write_file"], agent_id=agent_id,
                         capabilities=["document_generation"])

    def run(self, task_input: dict[str, Any]) -> dict[str, Any]:
        research = task_input["research"]
        out_name = task_input.get("filename") or f"drafts/{slugify(research['topic'])}.pptx"
        path = self.sandbox_path(out_name, "write_file")

        prs = Presentation()
        title = prs.slides.add_slide(prs.slide_layouts[0])
        title.shapes.title.text = research["topic"]
        title.placeholders[1].text = "Generated by AgentOS (DocGenAgent)"

        self._bullets(prs, "Summary", [research["summary"]])
        self._bullets(prs, "Key points", research["key_points"])
        self._bullets(prs, "Sources", research["sources"])

        path.parent.mkdir(parents=True, exist_ok=True)
        prs.save(path)
        return {"path": out_name, "slides": len(prs.slides), "topic": research["topic"]}

    @staticmethod
    def _bullets(prs: Presentation, heading: str, lines: list[str]) -> None:
        slide = prs.slides.add_slide(prs.slide_layouts[1])
        slide.shapes.title.text = heading
        body = slide.placeholders[1].text_frame
        body.text = lines[0]
        for line in lines[1:]:
            body.add_paragraph().text = line
        for para in body.paragraphs:
            for run in para.runs:
                run.font.size = Pt(18)
