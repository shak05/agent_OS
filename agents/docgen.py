"""DocGenAgent: turns research text into a small .pptx inside the sandbox."""
from __future__ import annotations

import re
from typing import Any, Optional

from pptx import Presentation
from pptx.enum.text import MSO_AUTO_SIZE
from pptx.util import Pt

from runtime.agent import Agent


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "report"


MAX_BULLETS = 6
MAX_CHARS = 220  # per bullet, so model output fits on a slide


def _clip(text: str, limit: int = MAX_CHARS) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


class DocGenAgent(Agent):
    """Builds slides from a research result: title, summary, key findings,
    optional reasoning / conclusions / assumptions, and sources & method.

    Refuses research results without a summary or findings, so a failed or
    empty analysis can never become a presentation.
    """

    def __init__(self, name: str = "DocGenAgent", agent_id: Optional[str] = None) -> None:
        super().__init__(name, permissions=["write_file"], agent_id=agent_id,
                         capabilities=["document_generation"])

    def run(self, task_input: dict[str, Any]) -> dict[str, Any]:
        research = task_input.get("research")
        if (not isinstance(research, dict) or not str(research.get("summary", "")).strip()
                or not research.get("key_points")):
            raise ValueError("DocGenAgent needs a research result with a summary and key findings")
        out_name = task_input.get("filename") or f"drafts/{slugify(research['topic'])}.pptx"
        path = self.sandbox_path(out_name, "write_file")

        made_by = (f"Analysis: {research['backend']} model {research['model']}"
                   if research.get("model") else "Analysis: research agent")
        prs = Presentation()
        title = prs.slides.add_slide(prs.slide_layouts[0])
        title.shapes.title.text = research["topic"]
        title.placeholders[1].text = f"Generated by AgentOS (DocGenAgent)\n{made_by}"

        self._bullets(prs, "Summary", [_clip(research["summary"], 700)])
        self._bullets(prs, "Key findings", research["key_points"])
        for key, heading in (("reasoning", "Supporting reasoning"), ("conclusions", "Conclusions"),
                             ("assumptions", "Assumptions & uncertainties")):
            if research.get(key):
                self._bullets(prs, heading, research[key])
        self._bullets(prs, "Sources & method", list(research.get("sources") or []) + [made_by])

        path.parent.mkdir(parents=True, exist_ok=True)
        prs.save(path)
        return {"path": out_name, "slides": len(prs.slides), "topic": research["topic"]}

    @staticmethod
    def _bullets(prs: Presentation, heading: str, lines: list[str]) -> None:
        slide = prs.slides.add_slide(prs.slide_layouts[1])
        slide.shapes.title.text = heading
        body = slide.placeholders[1].text_frame
        body.auto_size = MSO_AUTO_SIZE.TEXT_TO_FIT_SHAPE
        lines = [_clip(line, 700 if heading == "Summary" else MAX_CHARS) for line in lines[:MAX_BULLETS]]
        body.text = lines[0]
        for line in lines[1:]:
            body.add_paragraph().text = line
        size = Pt(18) if sum(len(line) for line in lines) < 400 else Pt(14)
        for para in body.paragraphs:
            for run in para.runs:
                run.font.size = size
